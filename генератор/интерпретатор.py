"""Исполнение спецификации: по строкам таблиц решений и шагов вычисляется ожидаемый результат."""
from __future__ import annotations

import copy
from dataclasses import dataclass, field
from datetime import datetime

from . import выражения as в
from .парсер import Метод, Объект, ОшибкаСпецификации, Тип

ПРЕДЕЛ_ШАГОВ = 10_000
ПРЕДЕЛ_ГЛУБИНЫ = 100
ДАТА_ТЕСТА = datetime(2026, 1, 15, 12, 0)


class ОшибкаМетода(Exception):
    """Ответ «Ошибка «текст»»: отказ, который видит пользователь."""


class Сбой(Exception):
    """Искусственный сбой шага."""


class НеЗавершается(ОшибкаСпецификации):
    pass


@dataclass
class Экз:
    """Экземпляр объекта спецификации в памяти интерпретатора."""
    объект: Объект
    реквизиты: dict = field(default_factory=dict)
    вызовы: list = field(default_factory=list)   # у внешнего объекта: (метод, аргументы)

    def __deepcopy__(self, memo) -> "Экз":
        if self.объект.внешний:
            return self   # внешний мир не копируется: отправленное письмо остаётся отправленным
        return Экз(self.объект, copy.deepcopy(self.реквизиты, memo), list(self.вызовы))


class Среда:
    def __init__(self, объекты: dict[str, Объект], сейчас: datetime = ДАТА_ТЕСТА):
        self.объекты = объекты
        self.сейчас = сейчас
        self.шаги = 0
        self.глубина = 0
        self.сбой: tuple[str, str, int] | None = None   # (объект, метод, шаг)
        self.прежние: dict | None = None   # реквизиты перед шагом, чью компенсацию выполняем
        self.значения_перечислений = {}
        for объект in объекты.values():
            for перечисление in объект.перечисления.values():
                for имя, _ in перечисление.значения:
                    self.значения_перечислений.setdefault(имя, []).append(перечисление.имя)

    # --- значения по умолчанию
    def по_умолчанию(self, тип: Тип, где: str, глубина: int = 0):
        if тип.по_умолчанию is not None:
            return self.вычислить(в.разобрать_выражение(тип.по_умолчанию, где), None, {}, {})
        if тип.необязательный:
            return None
        if тип.вид == "Строка":
            return где.rsplit(".", 1)[-1]
        if тип.вид == "Число":
            return 0
        if тип.вид == "Булево":
            return False
        if тип.вид == "Дата":
            return ДАТА_ТЕСТА
        if тип.вид == "Список":
            return []
        if тип.вид == "Ссылка":
            for объект in self.объекты.values():
                if тип.цель in объект.перечисления:
                    return объект.перечисления[тип.цель].значения[0][0]
            if тип.цель in self.объекты:
                if глубина > 3:
                    raise ОшибкаСпецификации(f"{где}: слишком глубокая цепочка ссылок")
                return self.создать(тип.цель, {}, глубина + 1)
            raise ОшибкаСпецификации(f"{где}: ссылка на неизвестный тип «{тип.цель}»")
        raise ОшибкаСпецификации(f"{где}: нет значения по умолчанию для {тип}")

    def создать(self, имя_объекта: str, значения: dict, глубина: int = 0) -> Экз:
        объект = self.объекты[имя_объекта]
        экз = Экз(объект)
        for реквизит in объект.реквизиты:
            if реквизит.имя in значения:
                экз.реквизиты[реквизит.имя] = значения[реквизит.имя]
            else:
                экз.реквизиты[реквизит.имя] = self.по_умолчанию(реквизит.тип, f"{имя_объекта}.{реквизит.имя}", глубина)
        for имя in значения:
            if объект.реквизит(имя) is None:
                raise ОшибкаСпецификации(f"{имя_объекта}: нет реквизита «{имя}»")
        return экз

    # --- вычисление
    def _шаг(self) -> None:
        self.шаги += 1
        if self.шаги > ПРЕДЕЛ_ШАГОВ:
            raise НеЗавершается(f"правило не завершается за {ПРЕДЕЛ_ШАГОВ} шагов")

    def вычислить(self, узел, экз: Экз | None, параметры: dict, локальные: dict):
        self._шаг()
        вид = узел[0]
        if вид in ("число", "строка", "булево", "дата"):
            return узел[1]
        if вид == "null":
            return None
        if вид == "сейчас":
            return self.сейчас
        if вид == "имя":
            return self.имя(узел[1], экз, параметры, локальные)
        if вид == "реквизит":
            хозяин = self.вычислить(узел[1], экз, параметры, локальные)
            return self.поле(хозяин, узел[2])
        if вид == "не":
            return not self.вычислить(узел[1], экз, параметры, локальные)
        if вид == "и":
            return bool(self.вычислить(узел[1], экз, параметры, локальные)) and bool(self.вычислить(узел[2], экз, параметры, локальные))
        if вид == "или":
            return bool(self.вычислить(узел[1], экз, параметры, локальные)) or bool(self.вычислить(узел[2], экз, параметры, локальные))
        if вид == "сравн":
            л = self.вычислить(узел[2], экз, параметры, локальные)
            п = self.вычислить(узел[3], экз, параметры, локальные)
            оп = узел[1]
            if оп == "=":
                return л == п
            if оп == "≠":
                return л != п
            if оп == "∈":
                return л in п
            if оп == "∉":
                return л not in п
            if л is None or п is None:
                return False
            return {"<": л < п, ">": л > п, "≤": л <= п, "≥": л >= п}[оп]
        if вид == "арифм":
            л = self.вычислить(узел[2], экз, параметры, локальные)
            п = self.вычислить(узел[3], экз, параметры, локальные)
            оп = узел[1]
            if оп == "+":
                return л + п if not isinstance(л, list) else л + (п if isinstance(п, list) else [п])
            if оп == "-":
                return л - п
            if оп == "*":
                return л * п
            return л / п
        if вид == "список":
            return [self.вычислить(э, экз, параметры, локальные) for э in узел[1]]
        if вид == "запись":
            return {имя: self.вычислить(э, экз, параметры, локальные) for имя, э in узел[1].items()}
        if вид == "вызов":
            return self.вызов(узел, экз, параметры, локальные)
        raise ОшибкаСпецификации(f"неизвестный узел {вид}")

    def имя(self, имя: str, экз: Экз | None, параметры: dict, локальные: dict):
        if имя in локальные:
            return локальные[имя]
        if имя in параметры:
            return параметры[имя]
        if экз is not None and имя in экз.реквизиты:
            return экз.реквизиты[имя]
        if имя in self.значения_перечислений:
            return имя
        raise ОшибкаСпецификации(f"неизвестное имя «{имя}»")

    def поле(self, хозяин, имя: str):
        if хозяин is None:
            return None
        if isinstance(хозяин, Экз):
            if имя not in хозяин.реквизиты:
                raise ОшибкаСпецификации(f"у объекта {хозяин.объект.имя} нет реквизита «{имя}»")
            return хозяин.реквизиты[имя]
        if isinstance(хозяин, dict):
            return хозяин.get(имя)
        raise ОшибкаСпецификации(f"у значения {хозяин!r} нет реквизита «{имя}»")

    def вызов(self, узел, экз: Экз | None, параметры: dict, локальные: dict):
        _, хозяин_узел, имя, аргументы_узлы = узел
        if хозяин_узел is None:
            if имя == "Прежнее":
                return self._прежнее(аргументы_узлы)
            if имя == "Отбор":
                список = self.вычислить(аргументы_узлы[0], экз, параметры, локальные)
                return [э for э in список if self.вычислить(аргументы_узлы[1], экз, параметры, {**локальные, "Э": э})]
            аргументы = [self.вычислить(а, экз, параметры, локальные) for а in аргументы_узлы]
            if имя == "Длина":
                return len(аргументы[0])
            if имя == "Первый":
                return аргументы[0][0] if аргументы[0] else None
            if имя == "КромеПервого":
                return аргументы[0][1:]
            if имя == "Последние":
                return аргументы[0][-аргументы[1]:] if аргументы[1] else []
            if экз is None:
                raise ОшибкаСпецификации(f"вызов «{имя}» вне объекта")
            return self.вызвать_метод(экз, имя, аргументы)
        хозяин = self.вычислить(хозяин_узел, экз, параметры, локальные)
        аргументы = [self.вычислить(а, экз, параметры, локальные) for а in аргументы_узлы]
        if not isinstance(хозяин, Экз):
            raise ОшибкаСпецификации(f"вызов «{имя}» у значения, которое не объект")
        return self.вызвать_метод(хозяин, имя, аргументы)

    def _прежнее(self, аргументы_узлы: list):
        if self.прежние is None:
            raise ОшибкаСпецификации("«Прежнее(…)» бывает только в компенсации шага")
        if len(аргументы_узлы) != 1 or аргументы_узлы[0][0] != "имя" or аргументы_узлы[0][1] not in self.прежние:
            raise ОшибкаСпецификации("в «Прежнее(…)» — имя реквизита объекта")
        return copy.deepcopy(self.прежние[аргументы_узлы[0][1]])

    # --- методы
    def вызвать_метод(self, экз: Экз, имя: str, аргументы: list):
        объект = экз.объект
        if имя not in объект.методы:
            raise ОшибкаСпецификации(f"у объекта {объект.имя} нет метода «{имя}»")
        метод = объект.методы[имя]
        if len(аргументы) != len(метод.параметры):
            raise ОшибкаСпецификации(f"{объект.имя}.{имя}: ожидается {len(метод.параметры)} параметров")
        if объект.внешний:
            экз.вызовы.append((имя, tuple(аргументы)))
            return None
        параметры = {п.имя: а for п, а in zip(метод.параметры, аргументы)}
        где = f"{объект.имя}.{имя}"
        self.глубина += 1
        if self.глубина > ПРЕДЕЛ_ГЛУБИНЫ:
            raise НеЗавершается(f"{где}: вложенность вызовов больше {ПРЕДЕЛ_ГЛУБИНЫ}, правило не завершается")
        прежние, self.прежние = self.прежние, None   # у вложенного метода своё «перед шагом»
        try:
            if метод.вид == "решения":
                return self._решения(метод, экз, параметры, где)
            return self._шаги(метод, экз, параметры, где)
        finally:
            self.глубина -= 1
            self.прежние = прежние

    def _решения(self, метод: Метод, экз: Экз, параметры: dict, где: str):
        for строка in метод.строки:
            условие = в.разобрать_условие(строка.условие, f"{где}: {строка.правило}")
            if условие is None or self.вычислить(условие, экз, параметры, {}):
                self.выполнить(в.разобрать_действия(строка.действия, где), экз, параметры, {})
                ответ = в.разобрать_ответ(строка.ответ, где)
                if ответ is None:
                    return None
                if ответ[0] == "ошибка":
                    raise ОшибкаМетода(ответ[1])
                return self.вычислить(ответ, экз, параметры, {})
        raise ОшибкаСпецификации(f"{где}: ни одна строка не подошла")

    def _шаги(self, метод: Метод, экз: Экз, параметры: dict, где: str):
        выполненные = []   # (строка, реквизиты перед ней)
        for строка in метод.строки:
            условие = в.разобрать_условие(строка.условие, f"{где}: {строка.правило}")
            if условие is not None and not self.вычислить(условие, экз, параметры, {}):
                continue
            if self.сбой == (экз.объект.имя, метод.имя, строка.шаг):
                # шаг со сбоем не выполнен; выполненные отменяются в обратном порядке
                for прошлая, перед in reversed(выполненные):
                    self.прежние = перед
                    try:
                        self.выполнить(в.разобрать_компенсацию(прошлая.компенсация, f"{где}: {прошлая.правило}"), экз, параметры, {})
                    except ОшибкаСпецификации as о:
                        if str(о).startswith(где):
                            raise
                        raise type(о)(f"{где}: компенсация шага «{прошлая.правило}»: {о}") from None
                    finally:
                        self.прежние = None
                raise Сбой(f"{где}: шаг {строка.шаг}")
            выполненные.append((строка, copy.deepcopy(экз.реквизиты)))
            self.выполнить(в.разобрать_действия(строка.действия, где), экз, параметры, {})
        return None

    def выполнить(self, действия: list, экз: Экз, параметры: dict, локальные: dict) -> None:
        for действие in действия:
            self._шаг()
            вид = действие[0]
            if вид == "присвоить":
                цель, выражение = действие[1], действие[2]
                значение = self.вычислить(выражение, экз, параметры, локальные)
                if цель[0] == "имя":
                    if цель[1] not in экз.реквизиты:
                        raise ОшибкаСпецификации(f"присваивание в неизвестный реквизит «{цель[1]}»")
                    экз.реквизиты[цель[1]] = значение
                else:
                    хозяин = self.вычислить(цель[1], экз, параметры, локальные)
                    if isinstance(хозяин, Экз):
                        хозяин.реквизиты[цель[2]] = значение
                    elif isinstance(хозяин, dict):
                        хозяин[цель[2]] = значение
                    else:
                        raise ОшибкаСпецификации(f"присваивание в «{цель[2]}» у значения, которое не объект")
            elif вид == "выполнить":
                self.вызов(действие[1], экз, параметры, локальные)
            elif вид == "для_каждого":
                for элемент in list(self.вычислить(действие[2], экз, параметры, локальные)):
                    self.выполнить(действие[3], экз, параметры, {**локальные, действие[1]: элемент})


def прочитать(экз: Экз) -> dict:
    """Реквизиты объекта в виде, который сравнивается с тем, что вернула привязка."""
    результат = {}
    for реквизит in экз.объект.реквизиты:
        значение = экз.реквизиты[реквизит.имя]
        if isinstance(значение, Экз):
            if значение.объект.внешний:
                continue
            значение = прочитать(значение)
        результат[реквизит.имя] = значение
    return результат
