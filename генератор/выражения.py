"""Язык выражений: разбор условий, эффектов и итогов в дерево."""
from __future__ import annotations

import re
from datetime import datetime

from .парсер import ОшибкаСпецификации

_ТОКЕН = re.compile(r"""
    (?P<пробел>\s+)
  | (?P<число>\d+(?:\.\d+)?)
  | (?P<строка>«[^»]*»)
  | (?P<оп>:=|≠|≤|≥|∈|[=<>+\-*/()\[\]{},;:.])
  | (?P<имя>[A-Za-zА-Яа-яЁё_][A-Za-zА-Яа-яЁё0-9_]*)
""", re.VERBOSE)

КЛЮЧЕВЫЕ = {"не", "и", "или", "Истина", "Ложь", "null", "Сейчас", "Ошибка", "Откат", "Для", "каждого", "из", "Дата"}


def _токены(текст: str, где: str) -> list[tuple[str, str]]:
    токены, позиция = [], 0
    while позиция < len(текст):
        m = _ТОКЕН.match(текст, позиция)
        if not m:
            raise ОшибкаСпецификации(f"{где}: непонятный символ «{текст[позиция]}» в «{текст}»")
        позиция = m.end()
        вид = m.lastgroup
        if вид == "пробел":
            continue
        значение = m.group(вид)
        if вид == "имя" and значение in КЛЮЧЕВЫЕ:
            вид = значение
        токены.append((вид, значение))
    токены.append(("конец", ""))
    return токены


class _Разбор:
    def __init__(self, текст: str, где: str):
        self.где = где
        self.текст = текст
        self.токены = _токены(текст, где)
        self.i = 0

    # --- служебное
    @property
    def текущий(self) -> tuple[str, str]:
        return self.токены[self.i]

    def это(self, *виды: str) -> bool:
        return self.текущий[0] in виды or (self.текущий[0] == "оп" and self.текущий[1] in виды)

    def взять(self, *виды: str) -> str:
        if виды and not self.это(*виды):
            raise ОшибкаСпецификации(f"{self.где}: ожидалось {' или '.join(виды)}, а в «{self.текст}» стоит «{self.текущий[1] or 'конец'}»")
        значение = self.текущий[1]
        self.i += 1
        return значение

    def конец(self) -> None:
        if self.текущий[0] != "конец":
            raise ОшибкаСпецификации(f"{self.где}: лишнее «{self.текущий[1]}» в «{self.текст}»")

    # --- выражения, от слабого приоритета к сильному
    def выражение(self):
        левое = self.и()
        while self.это("или"):
            self.взять()
            левое = ("или", левое, self.и())
        return левое

    def и(self):
        левое = self.сравнение()
        while self.это("и"):
            self.взять()
            левое = ("и", левое, self.сравнение())
        return левое

    def сравнение(self):
        левое = self.сумма()
        if self.это("=", "≠", "<", ">", "≤", "≥", "∈"):
            оп = self.взять()
            return ("сравн", оп, левое, self.сумма())
        return левое

    def сумма(self):
        левое = self.произведение()
        while self.это("+", "-"):
            оп = self.взять()
            левое = ("арифм", оп, левое, self.произведение())
        return левое

    def произведение(self):
        левое = self.унарное()
        while self.это("*", "/"):
            оп = self.взять()
            левое = ("арифм", оп, левое, self.унарное())
        return левое

    def унарное(self):
        if self.это("не"):
            self.взять()
            return ("не", self.унарное())
        if self.это("-"):
            self.взять()
            return ("арифм", "-", ("число", 0), self.унарное())
        return self.постфикс()

    def постфикс(self):
        узел = self.первичное()
        while self.это("."):
            self.взять()
            имя = self.взять("имя")
            if self.это("("):
                узел = ("вызов", узел, имя, self.аргументы())
            else:
                узел = ("реквизит", узел, имя)
        return узел

    def аргументы(self) -> list:
        self.взять("(")
        аргументы = []
        while not self.это(")"):
            аргументы.append(self.выражение())
            if self.это(","):
                self.взять()
        self.взять(")")
        return аргументы

    def первичное(self):
        вид, значение = self.текущий
        if вид == "число":
            self.взять()
            return ("число", float(значение) if "." in значение else int(значение))
        if вид == "строка":
            self.взять()
            return ("строка", значение[1:-1])
        if вид == "Истина" or вид == "Ложь":
            self.взять()
            return ("булево", вид == "Истина")
        if вид == "null":
            self.взять()
            return ("null",)
        if вид == "Сейчас":
            self.взять()
            return ("сейчас",)
        if вид == "Дата":
            self.взять()
            текст = self.взять("строка")[1:-1]
            return ("дата", datetime.fromisoformat(текст))
        if self.это("("):
            self.взять()
            узел = self.выражение()
            self.взять(")")
            return узел
        if self.это("["):
            self.взять()
            элементы = []
            while not self.это("]"):
                элементы.append(self.выражение())
                if self.это(","):
                    self.взять()
            self.взять("]")
            return ("список", элементы)
        if self.это("{"):
            self.взять()
            поля = {}
            while not self.это("}"):
                имя = self.взять("имя")
                self.взять(":")
                поля[имя] = self.выражение()
                if self.это(","):
                    self.взять()
            self.взять("}")
            return ("запись", поля)
        if вид == "имя":
            self.взять()
            if self.это("("):
                return ("вызов", None, значение, self.аргументы())
            return ("имя", значение)
        raise ОшибкаСпецификации(f"{self.где}: неожиданное «{значение or 'конец'}» в «{self.текст}»")

    # --- эффекты
    def эффекты(self) -> list:
        список = []
        while self.текущий[0] != "конец":
            список.append(self.эффект())
            if self.это(";"):
                self.взять()
        return список

    def эффект(self):
        if self.это("Для"):
            self.взять()
            self.взять("каждого")
            переменная = self.взять("имя")
            self.взять("из")
            список = self.выражение()
            self.взять(":")
            return ("для_каждого", переменная, список, self.эффекты())
        цель = self.постфикс()
        if self.это(":="):
            self.взять()
            if цель[0] not in ("имя", "реквизит"):
                raise ОшибкаСпецификации(f"{self.где}: слева от := должен быть реквизит, а не «{self.текст}»")
            return ("присвоить", цель, self.выражение())
        if цель[0] != "вызов":
            raise ОшибкаСпецификации(f"{self.где}: эффект «{self.текст}» — не присваивание и не вызов")
        return ("выполнить", цель)


def разобрать_условие(текст: str, где: str):
    """None, если условия нет (—)."""
    if текст.strip() in ("—", "-", ""):
        return None
    р = _Разбор(текст, где)
    узел = р.выражение()
    р.конец()
    return узел


def разобрать_выражение(текст: str, где: str):
    р = _Разбор(текст, где)
    узел = р.выражение()
    р.конец()
    return узел


def разобрать_эффекты(текст: str, где: str) -> list:
    if текст.strip() in ("—", "-", ""):
        return []
    р = _Разбор(текст, где)
    список = р.эффекты()
    р.конец()
    return список


def разобрать_итог(текст: str, где: str):
    """None — метод ничего не возвращает; ("ошибка", текст); иначе выражение."""
    текст = текст.strip()
    if текст in ("—", "-", ""):
        return None
    m = re.fullmatch(r"Ошибка\s*«([^»]*)»", текст)
    if m:
        return ("ошибка", m.group(1))
    return разобрать_выражение(текст, где)


def разобрать_при_сбое(текст: str, где: str):
    """None — не важно; ("откат",); иначе список эффектов."""
    текст = текст.strip()
    if текст in ("—", "-", ""):
        return None
    if текст == "Откат":
        return ("откат",)
    return разобрать_эффекты(текст, где)


def имена_в(узел, найденные: set[str] | None = None) -> set[str]:
    """Имена реквизитов и параметров верхнего уровня, от которых зависит выражение."""
    найденные = set() if найденные is None else найденные
    if узел is None:
        return найденные
    вид = узел[0]
    if вид == "имя":
        найденные.add(узел[1])
    elif вид == "реквизит":
        имена_в(узел[1], найденные)
    elif вид in ("сравн", "арифм"):
        имена_в(узел[2], найденные)
        имена_в(узел[3], найденные)
    elif вид in ("и", "или"):
        имена_в(узел[1], найденные)
        имена_в(узел[2], найденные)
    elif вид == "не":
        имена_в(узел[1], найденные)
    elif вид == "вызов":
        имена_в(узел[1], найденные)
        for а in узел[3]:
            имена_в(а, найденные)
    elif вид == "список":
        for э in узел[1]:
            имена_в(э, найденные)
    elif вид == "запись":
        for э in узел[1].values():
            имена_в(э, найденные)
    return найденные


def константы_в(узел, найденные: list | None = None) -> list:
    """Литералы и имена, с которыми сравниваются реквизиты: кандидаты для перебора."""
    найденные = [] if найденные is None else найденные
    if узел is None:
        return найденные
    вид = узел[0]
    if вид in ("число", "строка", "булево", "дата"):
        найденные.append(узел[1])
    elif вид == "null":
        найденные.append(None)
    elif вид == "имя":
        найденные.append(("имя", узел[1]))
    elif вид in ("сравн", "арифм"):
        константы_в(узел[2], найденные)
        константы_в(узел[3], найденные)
    elif вид in ("и", "или"):
        константы_в(узел[1], найденные)
        константы_в(узел[2], найденные)
    elif вид == "не":
        константы_в(узел[1], найденные)
    elif вид == "вызов":
        for а in узел[3]:
            константы_в(а, найденные)
    elif вид == "список":
        for э in узел[1]:
            константы_в(э, найденные)
    return найденные


ПРОСТЫЕ_ВЫЗОВЫ = {"Длина"}


def проверить_простое_условие(узел, где: str) -> None:
    """Правило ПростоеУсловие: в условии нет вызовов методов, Отбор и Последние."""
    if узел is None:
        return
    вид = узел[0]
    if вид == "вызов":
        if узел[1] is not None or узел[2] not in ПРОСТЫЕ_ВЫЗОВЫ:
            raise ОшибкаСпецификации(f"{где}: в условии вызов «{узел[2]}»; вызовы допустимы только в эффектах и итогах")
        for а in узел[3]:
            проверить_простое_условие(а, где)
    elif вид in ("сравн", "арифм"):
        проверить_простое_условие(узел[2], где)
        проверить_простое_условие(узел[3], где)
    elif вид in ("и", "или"):
        проверить_простое_условие(узел[1], где)
        проверить_простое_условие(узел[2], где)
    elif вид == "не":
        проверить_простое_условие(узел[1], где)
    elif вид == "реквизит":
        проверить_простое_условие(узел[1], где)
