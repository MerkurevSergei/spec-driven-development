ПРЕДЕЛ_ПЕРЕБОРА = 5000


# ---------------------------------------------------------------- кандидаты значений

def кандидаты(тип: Тип, константы: list, среда: Среда, где: str) -> list:
    умолч = среда.по_умолчанию(тип, где)
    значения: list = [умолч]
    if тип.вид == "Булево":
        значения += [False, True]
    elif тип.вид == "Число":
        числа = {0, 1}
        for к in константы:
            if isinstance(к, (int, float)) and not isinstance(к, bool):
                числа |= {к, к - 1, к + 1}
        if тип.неотрицательное:
            числа = {ч for ч in числа if ч >= 0}
        значения += sorted(числа)
    elif тип.вид == "Строка":
        значения += [к for к in константы if isinstance(к, str)]
    elif тип.вид == "Дата":
        значения += [ДАТА_ТЕСТА]
    elif тип.вид == "Список":
        значения += [[], [среда.по_умолчанию(тип.элемент, где)]]
    elif тип.вид == "Ссылка":
        for объект in среда.объекты.values():
            if тип.цель in объект.перечисления:
                значения += [имя for имя, _ in объект.перечисления[тип.цель].значения]
    if тип.необязательный:
        значения.append(None)
    уникальные = []
    for з in значения:
        if з not in уникальные:
            уникальные.append(з)
    return уникальные


# ---------------------------------------------------------------- подбор состояния

class Подбор:
    def __init__(self, объекты: dict[str, Объект]):
        self.объекты = объекты

    def среда(self) -> Среда:
        return Среда(self.объекты)

    def состояния(self, объект: Объект, метод: Метод, условия: list):
        """Перебор значений реквизитов и параметров, упомянутых в условиях метода."""
        среда = self.среда()
        имена: set[str] = set()
        константы: list = []
        for условие in условия:
            в.имена_в(условие, имена)
            в.константы_в(условие, константы)
        переменные = []
        for реквизит in объект.реквизиты:
            if реквизит.имя in имена:
                переменные.append(("реквизит", реквизит.имя, кандидаты(реквизит.тип, константы, среда, f"{объект.имя}.{реквизит.имя}")))
        for параметр in метод.параметры:
            переменные.append(("параметр", параметр.имя, кандидаты(параметр.тип, константы, среда, f"{объект.имя}.{метод.имя}.{параметр.имя}")))
        for i, набор in enumerate(itertools.product(*[к for _, _, к in переменные])):
            if i >= ПРЕДЕЛ_ПЕРЕБОРА:
                break
            реквизиты = {имя: з for (вид, имя, _), з in zip(переменные, набор) if вид == "реквизит"}
            параметры = {имя: з for (вид, имя, _), з in zip(переменные, набор) if вид == "параметр"}
            yield реквизиты, параметры

    def истинно(self, объект: Объект, условие, реквизиты: dict, параметры: dict) -> bool:
        if условие is None:
            return True
        среда = self.среда()
        экз = среда.создать(объект.имя, dict(реквизиты))
        return bool(среда.вычислить(условие, экз, параметры, {}))

    def для_строки(self, объект: Объект, метод: Метод, условия: list, i: int):
        """Состояние, где условия строк до i ложны, а условие строки i истинно."""
        for реквизиты, параметры in self.состояния(объект, метод, условия):
            if any(self.истинно(объект, у, реквизиты, параметры) for у in условия[:i]):
                continue
            if self.истинно(объект, условия[i], реквизиты, параметры):
                return реквизиты, параметры
        return None

    def для_шагов(self, объект: Объект, метод: Метод, условия: list, ложный: int | None):
        """Состояние, где условия всех шагов истинны, кроме шага с индексом `ложный`."""
        for реквизиты, параметры in self.состояния(объект, метод, условия):
            подходит = True
            for j, условие in enumerate(условия):
                ожидается = j != ложный
                if self.истинно(объект, условие, реквизиты, параметры) != ожидается:
                    подходит = False
                    break
            if подходит:
                return реквизиты, параметры
        return None


# ---------------------------------------------------------------- прогон и запись теста

def репр(значение) -> str:
    if isinstance(значение, datetime):
        return f"datetime({значение.year}, {значение.month}, {значение.day}, {значение.hour}, {значение.minute})"
    if isinstance(значение, list):
        return "[" + ", ".join(репр(э) for э in значение) + "]"
    if isinstance(значение, tuple):
        return "(" + ", ".join(репр(э) for э in значение) + ("," if len(значение) == 1 else "") + ")"
    if isinstance(значение, dict):
        return "{" + ", ".join(f"{репр(к)}: {репр(з)}" for к, з in значение.items()) + "}"
    return repr(значение)


class Запись:
    """Код создания объекта в тесте: внешние объекты — регистраторы, ссылки — вложенные создать()."""

    def __init__(self, объекты: dict[str, Объект]):
        self.объекты = объекты
        self.внешние: list[tuple[str, str]] = []   # (переменная, объект)

    def создание(self, экз: Экз) -> str:
        части = []
        for реквизит in экз.объект.реквизиты:
            значение = экз.реквизиты[реквизит.имя]
            if isinstance(значение, Экз):
                if значение.объект.внешний:
                    переменная = f"внешний_{значение.объект.имя.lower()}"
                    if (переменная, значение.объект.имя) not in self.внешние:
                        self.внешние.append((переменная, значение.объект.имя))
                    части.append(f"{репр(реквизит.имя)}: {переменная}")
                    continue
                части.append(f"{репр(реквизит.имя)}: {self.создание(значение)}")
            else:
                части.append(f"{репр(реквизит.имя)}: {репр(значение)}")
        return f"привязка.создать({репр(экз.объект.имя)}, {{{', '.join(части)}}})"


class Генератор:
    def __init__(self, объекты: dict[str, Объект]):
        self.объекты = объекты
        self.подбор = Подбор(объекты)
        self.группы: dict[str, tuple[str, list]] = {}   # класс → (описание, [(имя, описание, тело)])
        self.группа = ("", "")
        for объект in объекты.values():
            for перечисление in объект.перечисления.values():
                _ЗНАЧЕНИЯ_ПЕРЕЧИСЛЕНИЙ.update(имя for имя, _ in перечисление.значения)
        self.имена: set[str] = set()

    # --- вход
    def все(self) -> str:
        for объект in self.объекты.values():
            if объект.внешний:
                continue
            self.группа = (f"Тест_{объект.имя}", f"{объект.имя}: реквизиты, перечисления и реализация")
            self.реквизиты(объект)
            for перечисление in объект.перечисления.values():
                self.перечисление(объект, перечисление)
            self.реализация(объект)
            for метод in объект.методы.values():
                параметры = ", ".join(п.имя for п in метод.параметры)
                self.группа = (f"Тест_{объект.имя}_{метод.имя}", f"{объект.имя}.{метод.имя}({параметры})")
                if метод.вид == "решения":
                    self.решения(объект, метод)
                else:
                    self.шаги(объект, метод)
                self.примеры(объект, метод)
        return self.текст()

    def тест(self, имя: str, описание: list[str], тело: list[str]) -> None:
        if имя in self.имена:
            raise ОшибкаСпецификации(f"имя теста {имя} повторяется")
        self.имена.add(имя)
        класс, описание_группы = self.группа
        self.группы.setdefault(класс, (описание_группы, []))[1].append((имя, описание, тело))

    def текст(self) -> str:
        строки = [
            "# Сгенерировано по спецификации: не править руками, перегенерировать.",
            "import unittest",
            "from datetime import datetime",
            "",
            "from tests import привязка",
        ]
        for класс, (описание_группы, тесты) in self.группы.items():
            while строки[-1] == "":
                строки.pop()
            строки += ["", "", f"class {класс}(unittest.TestCase):"]
            строки += _документация([описание_группы], "    ")
            строки.append("")
            for имя, описание, тело in тесты:
                строки.append(f"    def {имя}(self):")
                строки += _документация(описание, "        ")
                строки += ["        " + с for с in тело]
                строки.append("")
        return "\n".join(строки).rstrip()

    # --- таблицы данных
    def реквизиты(self, объект: Объект) -> None:
        среда = self.подбор.среда()
        экз = среда.создать(объект.имя, {})
        запись = Запись(self.объекты)
        создание = запись.создание(экз)
        тело = [f"{п} = привязка.внешний({репр(о)})" for п, о in запись.внешние]
        тело += [
            f"объект = {создание}",
            f"self.assertEqual(привязка.прочитать(объект), {репр(прочитать(экз))})",
        ]
        имена = ", ".join(р.имя for р in объект.реквизиты)
        self.тест(f"test_{объект.имя}_Реквизиты", [f"Реквизиты {имена} создаются со значениями по умолчанию и читаются без потерь"], тело)

    def перечисление(self, объект: Объект, перечисление) -> None:
        значения = [имя for имя, _ in перечисление.значения]
        self.тест(f"test_{объект.имя}_{перечисление.имя}", [f"{перечисление.имя}: значения {', '.join(значения)} в этом порядке"], [
            f"self.assertEqual(привязка.значения_перечисления({репр(перечисление.имя)}), {репр(значения)})",
        ])

    def реализация(self, объект: Объект) -> None:
        модуль = объект.свойства.get("Модуль", "").strip("`")
        self.тест(f"test_{объект.имя}_Реализация", [f"Класс {объект.имя} есть в модуле {модуль}"], [
            f"self.assertIsNotNone(привязка.класс({репр(объект.имя)}), {репр(f'в модуле {модуль} нет класса {объект.имя}')})",
        ])

    # --- таблица решений
    def решения(self, объект: Объект, метод: Метод) -> None:
        где = f"{объект.имя}.{метод.имя}"
        условия = []
        for строка in метод.строки:
            условие = в.разобрать_условие(строка.условие, f"{где}: {строка.правило}")
            в.проверить_простое_условие(условие, f"{где}: {строка.правило}")
            условия.append(условие)
        for i, строка in enumerate(метод.строки):
            найдено = self.подбор.для_строки(объект, метод, условия, i)
            if найдено is None:
                if not any(п.правило == строка.правило for п in метод.примеры):
                    raise ОшибкаСпецификации(f"{где}: для строки «{строка.правило}» не подобрать состояние; добавьте таблицу Примеры")
                continue
            реквизиты, параметры = найдено
            if _пусто(строка.условие):
                когда = "иначе" if i else "всегда"
            else:
                когда = f"если {строка.условие}"
            self.прогон(объект, метод, строка.правило, реквизиты, параметры, f"test_{объект.имя}_{метод.имя}_{строка.правило}",
                        [f"{строка.правило}: {когда} → {_исход(строка)}"])

    def примеры(self, объект: Объект, метод: Метод) -> None:
        где = f"{объект.имя}.{метод.имя}: Примеры"
        среда = self.подбор.среда()
        for n, пример in enumerate(метод.примеры, 1):
            реквизиты = {} if пример.реквизиты.strip() == "—" else среда.вычислить(в.разобрать_выражение(пример.реквизиты, где), None, {}, {})
            параметры = {} if пример.параметры.strip() == "—" else среда.вычислить(в.разобрать_выражение(пример.параметры, где), None, {}, {})
            if not any(с.правило == пример.правило for с in метод.строки):
                raise ОшибкаСпецификации(f"{где}: правила «{пример.правило}» нет в методе")
            строка = next(с for с in метод.строки if с.правило == пример.правило)
            self.прогон(объект, метод, пример.правило, реквизиты, параметры, f"test_{объект.имя}_{метод.имя}_{пример.правило}_пример{n}",
                        [f"Пример {n} к правилу {пример.правило} → {_исход(строка)}"])

    def прогон(self, объект: Объект, метод: Метод, правило: str, реквизиты: dict, параметры: dict, имя: str,
               описание: list[str], сбой: tuple | None = None) -> None:
        среда = self.подбор.среда()
        среда.сбой = сбой
        экз = среда.создать(объект.имя, dict(реквизиты))
        запись = Запись(self.объекты)
        создание = запись.создание(экз)
        аргументы = ", ".join(репр(параметры[п.имя]) for п in метод.параметры)
        вызов = f"объект.{метод.имя}({аргументы})"
        тело = [f"{п} = привязка.внешний({репр(о)})" for п, о in запись.внешние]
        тело += [f"объект = {создание}", f"привязка.сейчас({репр(среда.сейчас)})"]
        исход = None
        ошибка = None
        try:
            исход = среда.вызвать_метод(экз, метод.имя, [параметры[п.имя] for п in метод.параметры])
        except ОшибкаМетода as о:
            ошибка = str(о)
        except Сбой:
            ошибка = "сбой"
        if сбой is not None:
            тело.append(f"with привязка.сбой_на_шаге({репр(сбой[0])}, {репр(сбой[1])}, {сбой[2]}):")
            тело.append("    with self.assertRaises(привязка.Сбой):")
            тело.append(f"        {вызов}")
        elif ошибка is not None:
            тело.append("with self.assertRaises(Exception) as ошибка:")
            тело.append(f"    {вызов}")
            тело.append(f"self.assertIn({репр(ошибка)}, str(ошибка.exception))")
        elif метод.тип_итога is not None:
            тело.append(f"self.assertEqual({вызов}, {репр(исход)})")
        else:
            тело.append(вызов)
        тело.append(f"self.assertEqual(привязка.прочитать(объект), {репр(прочитать(экз))})")
        for имя_инварианта, условие in объект.инварианты:
            узел = в.разобрать_условие(условие, f"{объект.имя}: {имя_инварианта}")
            if not среда.вычислить(узел, экз, {}, {}):
                raise ОшибкаСпецификации(f"{объект.имя}.{метод.имя}: правило «{правило}» нарушает инвариант «{имя_инварианта}»")
        for переменная, имя_объекта in запись.внешние:
            вызовы = self._вызовы(экз, имя_объекта)
            тело.append(f"self.assertEqual({переменная}.вызовы, {репр(вызовы)})")
        self.тест(имя, описание + self._вход_и_итог(объект, метод, среда, реквизиты, параметры, экз, исход, ошибка, сбой), тело)

    def _вход_и_итог(self, объект: Объект, метод: Метод, среда: Среда, реквизиты: dict, параметры: dict,
                     экз: Экз, исход, ошибка, сбой) -> list[str]:
        """Две строки описания: что подобрал генератор и что вычислила спецификация."""
        вход = [f"{к} = {_человеку(з)}" for к, з in реквизиты.items()
                if з != среда.по_умолчанию(объект.реквизит(к).тип, f"{объект.имя}.{к}")]
        вход += [f"{к} = {_человеку(з)}" for к, з in параметры.items()]
        строки = [f"Вход: {'; '.join(вход) if вход else 'значения по умолчанию'}"]
        if ошибка is not None and сбой is None:
            строки.append(f"Ожидается: Ошибка «{ошибка}», реквизиты не меняются")
            return строки
        до = прочитать(self.подбор.среда().создать(объект.имя, dict(реквизиты)))
        ожидается = [f"{к} = {_человеку(з)}" for к, з in прочитать(экз).items() if з != до.get(к)]
        if метод.тип_итога is not None and сбой is None:
            ожидается.insert(0, f"итог {_человеку(исход)}")
        for значение in экз.реквизиты.values():
            if isinstance(значение, Экз) and значение.объект.внешний:
                for метод_вн, аргументы in значение.вызовы:
                    ожидается.append(f"{значение.объект.имя}.{метод_вн}({', '.join(_человеку(а) for а in аргументы)})")
        строки.append(f"Ожидается: {'; '.join(ожидается) if ожидается else 'ничего не меняется'}")
        return строки

    def _вызовы(self, экз: Экз, имя_объекта: str) -> list:
        for значение in экз.реквизиты.values():
            if isinstance(значение, Экз) and значение.объект.имя == имя_объекта:
                return list(значение.вызовы)
        return []

    # --- таблица шагов
    def шаги(self, объект: Объект, метод: Метод) -> None:
        где = f"{объект.имя}.{метод.имя}"
        условия = []
        for строка in метод.строки:
            условие = в.разобрать_условие(строка.условие, f"{где}: {строка.правило}")
            в.проверить_простое_условие(условие, f"{где}: {строка.правило}")
            условия.append(условие)
        найдено = self.подбор.для_шагов(объект, метод, условия, None)
        if найдено is None:
            raise ОшибкаСпецификации(f"{где}: не подобрать состояние, где все шаги выполняются")
        реквизиты, параметры = найдено
        шаги = ", ".join(f"{с.шаг} {с.правило}" for с in метод.строки)
        self.прогон(объект, метод, "ВсеШаги", реквизиты, параметры, f"test_{объект.имя}_{метод.имя}_ВсеШаги",
                    [f"Все шаги по порядку: {шаги}"])
        for j, строка in enumerate(метод.строки):
            if условия[j] is not None:
                без = self.подбор.для_шагов(объект, метод, условия, j)
                if без is not None:
                    self.прогон(объект, метод, строка.правило, без[0], без[1], f"test_{объект.имя}_{метод.имя}_Без{строка.правило}",
                                [f"Шаг {строка.шаг} {строка.правило} пропускается: условие «{строка.условие}» ложно"])
            отмена = [с for с in метод.строки[:j] if с.компенсация.strip() not in ("—", "-", "")]
            if отмена:
                компенсации = ", ".join(f"{с.шаг} {с.правило}" for с in reversed(отмена))
                self.прогон(объект, метод, строка.правило, реквизиты, параметры,
                            f"test_{объект.имя}_{метод.имя}_СбойНаШаге{строка.шаг}",
                            [f"Сбой на шаге {строка.шаг} {строка.правило} → компенсация шагов {компенсации}"], сбой=(объект.имя, метод.имя, строка.шаг))


_ЗНАЧЕНИЯ_ПЕРЕЧИСЛЕНИЙ: set[str] = set()   # заполняет Генератор: такие строки пишутся без кавычек


def _пусто(ячейка: str) -> bool:
    return ячейка.strip() in ("—", "-", "")


def _исход(строка) -> str:
    части = []
    if not _пусто(строка.эффект):
        части.append(строка.эффект)
    if not _пусто(строка.итог):
        части.append(строка.итог if строка.итог.startswith("Ошибка") else f"итог {строка.итог}")
    return "; ".join(части) or "ничего не меняется"


def _человеку(значение) -> str:
    """Значение так, как оно записано в спецификации."""
    if значение is None:
        return "null"
    if значение is True:
        return "Истина"
    if значение is False:
        return "Ложь"
    if isinstance(значение, datetime):
        return f"Дата«{значение:%Y-%m-%d %H:%M}»"
    if isinstance(значение, str):
        return значение if значение in _ЗНАЧЕНИЯ_ПЕРЕЧИСЛЕНИЙ else f"«{значение}»"
    if isinstance(значение, list):
        return "[" + ", ".join(_человеку(э) for э in значение) + "]"
    if isinstance(значение, dict):
        return "{" + ", ".join(f"{к}: {_человеку(з)}" for к, з in значение.items()) + "}"
    if isinstance(значение, Экз):
        return значение.объект.имя
    return str(значение)


def _документация(строки: list[str], отступ: str) -> list[str]:
    """Строка документации Python: её первую строку печатает unittest -v рядом с именем теста."""
    чистые = [с.replace("\\", "\\\\").replace(chr(34) * 3, chr(39) * 3) for с in строки]
    if len(чистые) == 1:
        return [f'{отступ}"""{чистые[0]}"""']
    return [f'{отступ}"""{чистые[0]}', *[отступ + с for с in чистые[1:]], f'{отступ}"""']

