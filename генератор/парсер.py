"""Чтение документов спецификации в модель: объекты, реквизиты, перечисления, методы."""
from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path


class ОшибкаСпецификации(Exception):
    """Документ не соответствует стандарту; текст говорит, где и что."""


@dataclass
class Тип:
    вид: str                      # Строка, Число, Булево, Дата, Ссылка, Список
    цель: str | None = None       # имя объекта или перечисления для Ссылка
    элемент: Тип | None = None    # тип элемента для Список
    длина: int | None = None
    точность: int = 0
    неотрицательное: bool = False
    необязательный: bool = False
    по_умолчанию: str | None = None   # исходный текст выражения после "="

    def __str__(self) -> str:
        if self.вид == "Ссылка":
            основа = f'Ссылка."{self.цель}"'
        elif self.вид == "Список":
            основа = f"Список.{self.элемент}"
        elif self.вид == "Число":
            части = [str(self.длина), str(self.точность)]
            if self.неотрицательное:
                части.append("Неотрицательное")
            основа = f"Число({','.join(части)})"
        elif self.вид == "Строка" and self.длина:
            основа = f"Строка({self.длина})"
        else:
            основа = self.вид
        return основа + ("?" if self.необязательный else "")


@dataclass
class Реквизит:
    имя: str
    описание: str
    тип: Тип


@dataclass
class Перечисление:
    имя: str
    значения: list[tuple[str, str]]   # (имя, описание)


@dataclass
class Параметр:
    имя: str
    тип: Тип


@dataclass
class Строка:
    """Строка таблицы решений или шагов; ячейки — исходный текст."""
    правило: str
    условие: str
    эффект: str
    итог: str = "—"        # у таблицы решений
    шаг: int | None = None  # у таблицы шагов
    при_сбое: str = "—"    # у таблицы шагов


@dataclass
class Пример:
    правило: str
    реквизиты: str
    параметры: str


@dataclass
class Метод:
    имя: str
    параметры: list[Параметр]
    тип_итога: Тип | None
    вид: str | None = None          # "решения", "шаги" или None у внешнего объекта
    строки: list[Строка] = field(default_factory=list)
    примеры: list[Пример] = field(default_factory=list)


@dataclass
class Объект:
    имя: str
    путь: Path
    реквизиты: list[Реквизит] = field(default_factory=list)
    инварианты: list[tuple[str, str]] = field(default_factory=list)   # (правило, условие)
    перечисления: dict[str, Перечисление] = field(default_factory=dict)
    методы: dict[str, Метод] = field(default_factory=dict)
    свойства: dict[str, str] = field(default_factory=dict)

    @property
    def внешний(self) -> bool:
        return self.свойства.get("Внешний", "").strip().lower() == "да"

    def реквизит(self, имя: str) -> Реквизит | None:
        return next((р for р in self.реквизиты if р.имя == имя), None)


# ---------------------------------------------------------------- markdown

@dataclass
class Раздел:
    уровень: int
    заголовок: str
    таблицы: list[list[list[str]]] = field(default_factory=list)  # таблица = строки = ячейки


_ССЫЛКА = re.compile(r"\[([^\]]*)\]\([^)]*\)")


def _ячейки(строка: str) -> list[str]:
    тело = строка.strip()
    if тело.startswith("|"):
        тело = тело[1:]
    if тело.endswith("|"):
        тело = тело[:-1]
    return [я.strip().replace("\\|", "|") for я in re.split(r"(?<!\\)\|", тело)]


_ИМЯ = re.compile(r"[A-ZА-ЯЁ][A-Za-zА-Яа-яЁё0-9]*")


def проверить_имя(имя: str, где: str) -> str:
    if not _ИМЯ.fullmatch(имя):
        raise ОшибкаСпецификации(f"{где}: имя «{имя}» — с заглавной буквы, только буквы и цифры")
    return имя


def _разделы(текст: str, путь: Path) -> tuple[str, list[Раздел]]:
    заголовок_документа = None
    назначение_есть = False
    разделы: list[Раздел] = []
    текущая_таблица: list[list[str]] | None = None
    for строка in текст.splitlines():
        if заголовок_документа is not None and not разделы and строка.strip() and not назначение_есть:
            if not строка.startswith("\\#"):
                raise ОшибкаСпецификации(f"{путь.name}: после заголовка ожидается комментарий о назначении (строка «\\# …»)")
            назначение_есть = True
            continue
        if строка.startswith("|"):
            ячейки = _ячейки(строка)
            if all(re.fullmatch(r":?-+:?", я) for я in ячейки if я):
                continue  # разделитель шапки
            if текущая_таблица is None:
                текущая_таблица = []
                if not разделы:
                    raise ОшибкаСпецификации(f"{путь}: таблица до первого раздела")
                разделы[-1].таблицы.append(текущая_таблица)
            текущая_таблица.append(ячейки)
            continue
        текущая_таблица = None
        m = re.match(r"^(#{1,3})\s+(.*)$", строка)
        if m:
            уровень = len(m.group(1))
            if уровень == 1:
                заголовок_документа = m.group(2).strip()
            else:
                разделы.append(Раздел(уровень, m.group(2).strip()))
    if заголовок_документа is None:
        raise ОшибкаСпецификации(f"{путь}: нет заголовка документа")
    if not назначение_есть:
        raise ОшибкаСпецификации(f"{путь.name}: нет комментария о назначении после заголовка")
    return заголовок_документа, разделы


# ---------------------------------------------------------------- типы

def _без_ссылки(текст: str) -> str:
    return _ССЫЛКА.sub(r"\1", текст).strip()


def разобрать_тип(текст: str, где: str) -> Тип:
    текст = _без_ссылки(текст)
    по_умолчанию = None
    m = re.match(r"^(.*?)\s*=\s*(.+)$", текст)
    if m:
        текст, по_умолчанию = m.group(1).strip(), m.group(2).strip()
    необязательный = текст.endswith("?")
    if необязательный:
        текст = текст[:-1].strip()
    тип = _разобрать_основу(текст, где)
    тип.необязательный = необязательный
    тип.по_умолчанию = по_умолчанию
    return тип


def _разобрать_основу(текст: str, где: str) -> Тип:
    if текст == "Булево" or текст == "Дата":
        return Тип(текст)
    m = re.fullmatch(r"Строка(?:\((\d+)\))?", текст)
    if m:
        return Тип("Строка", длина=int(m.group(1)) if m.group(1) else None)
    m = re.fullmatch(r"Число\((\d+)(?:,\s*(\d+))?(?:,\s*Неотрицательное)?\)", текст)
    if m:
        return Тип("Число", длина=int(m.group(1)), точность=int(m.group(2) or 0),
                   неотрицательное="Неотрицательное" in текст)
    m = re.fullmatch(r'Ссылка\."([^"]+)"', текст)
    if m:
        return Тип("Ссылка", цель=m.group(1))
    m = re.fullmatch(r"Список\.(.+)", текст)
    if m:
        return Тип("Список", элемент=_разобрать_основу(m.group(1), где))
    raise ОшибкаСпецификации(f"{где}: неизвестный тип «{текст}»")


def _разбить_параметры(текст: str) -> list[str]:
    части, глубина, текущая = [], 0, ""
    for символ in текст:
        if символ == "(":
            глубина += 1
        elif символ == ")":
            глубина -= 1
        if символ == "," and глубина == 0:
            части.append(текущая)
            текущая = ""
        else:
            текущая += символ
    if текущая.strip():
        части.append(текущая)
    return [ч.strip() for ч in части]


def разобрать_заголовок_метода(заголовок: str, где: str) -> Метод:
    текст = заголовок.strip()
    m = re.match(r"([^\s(]+)\(", текст)
    глубина, конец = 0, None
    for i, символ in enumerate(текст):
        if символ == "(":
            глубина += 1
        elif символ == ")":
            глубина -= 1
            if глубина == 0:
                конец = i
                break
    if not m or конец is None:
        raise ОшибкаСпецификации(f"{где}: заголовок метода «{заголовок}» не вида Имя(Параметр: Тип): Тип")
    имя_метода = m.group(1)
    внутри = текст[m.end():конец]
    хвост = текст[конец + 1:].strip()
    параметры = []
    for часть in _разбить_параметры(внутри):
        if ":" not in часть:
            raise ОшибкаСпецификации(f"{где}: у параметра «{часть}» метода {имя_метода} нет типа")
        имя, тип = часть.split(":", 1)
        параметры.append(Параметр(имя.strip(), разобрать_тип(тип.strip(), где)))
    тип_итога = None
    if хвост:
        if not хвост.startswith(":"):
            raise ОшибкаСпецификации(f"{где}: после скобок метода {имя_метода} ожидается «: Тип»")
        тип_итога = разобрать_тип(хвост[1:].strip(), где)
    for параметр in параметры:
        проверить_имя(параметр.имя, где)
    return Метод(проверить_имя(имя_метода, где), параметры, тип_итога)


# ---------------------------------------------------------------- документ

КОЛОНКИ_РЕШЕНИЙ = ["Правило", "Условие", "Эффект", "Итог"]
КОЛОНКИ_ШАГОВ = ["Правило", "Шаг", "Условие", "Эффект", "При сбое"]
КОЛОНКИ_ПРИМЕРОВ = ["Правило", "Реквизиты", "Параметры"]


def _шапка(таблица: list[list[str]]) -> list[str]:
    return [_без_ссылки(я) for я in таблица[0]]


ПОРЯДОК_РАЗДЕЛОВ = ["Реквизиты", "Типы и перечисления", "Методы", "Техническое соответствие"]


def разобрать_документ(путь: Path) -> Объект:
    имя, разделы = _разделы(путь.read_text(encoding="utf-8"), путь)
    объект = Объект(проверить_имя(имя, путь.name), путь)
    текущий = None
    встреченные: list[str] = []
    for раздел in разделы:
        где = f"{путь.name}: {раздел.заголовок}"
        if раздел.уровень == 2:
            текущий = раздел.заголовок
            if текущий not in ПОРЯДОК_РАЗДЕЛОВ:
                raise ОшибкаСпецификации(f"{где}: неизвестный раздел")
            if встреченные and ПОРЯДОК_РАЗДЕЛОВ.index(текущий) <= ПОРЯДОК_РАЗДЕЛОВ.index(встреченные[-1]):
                raise ОшибкаСпецификации(f"{где}: разделы идут в порядке {', '.join(ПОРЯДОК_РАЗДЕЛОВ)}")
            встреченные.append(текущий)
            if текущий == "Реквизиты":
                объект.реквизиты = _реквизиты(раздел.таблицы, где)
                объект.инварианты = _инварианты(раздел.таблицы, где)
            elif текущий == "Техническое соответствие":
                for таблица in раздел.таблицы:
                    if _шапка(таблица)[:2] == ["Свойство", "Значение"]:
                        for строка in таблица[1:]:
                            объект.свойства[строка[0]] = строка[1]
        elif текущий == "Типы и перечисления":
            объект.перечисления[раздел.заголовок] = _перечисление(раздел, где)
        elif текущий == "Методы":
            метод = _метод(раздел, где)
            объект.методы[метод.имя] = метод
    for обязательный in ("Реквизиты", "Техническое соответствие"):
        if обязательный not in встреченные:
            raise ОшибкаСпецификации(f"{путь.name}: нет раздела «{обязательный}»")
    return объект


def _реквизиты(таблицы: list[list[list[str]]], где: str) -> list[Реквизит]:
    for таблица in таблицы:
        if _шапка(таблица) == ["Имя", "Описание", "Тип"]:
            return [Реквизит(проверить_имя(с[0], где), с[1], разобрать_тип(с[2], f"{где}: {с[0]}")) for с in таблица[1:]]
    raise ОшибкаСпецификации(f"{где}: нет таблицы Имя | Описание | Тип")


def _инварианты(таблицы: list[list[list[str]]], где: str) -> list[tuple[str, str]]:
    for таблица in таблицы:
        if _шапка(таблица) == ["Правило", "Условие"]:
            return [(проверить_имя(с[0], где), с[1]) for с in таблица[1:]]
    return []


def _перечисление(раздел: Раздел, где: str) -> Перечисление:
    for таблица in раздел.таблицы:
        if _шапка(таблица)[:2] == ["Имя", "Описание"]:
            return Перечисление(проверить_имя(раздел.заголовок, где), [(проверить_имя(с[0], где), с[1]) for с in таблица[1:]])
    raise ОшибкаСпецификации(f"{где}: нет таблицы перечисления")


def _метод(раздел: Раздел, где: str) -> Метод:
    метод = разобрать_заголовок_метода(раздел.заголовок, где)
    for таблица in раздел.таблицы:
        шапка = _шапка(таблица)
        if шапка == КОЛОНКИ_РЕШЕНИЙ:
            метод.вид = "решения"
            метод.строки = [Строка(проверить_имя(с[0], где), с[1], с[2], итог=с[3]) for с in таблица[1:]]
            if метод.строки and метод.строки[-1].условие != "—":
                raise ОшибкаСпецификации(f"{где}: последняя строка таблицы решений должна быть без условия")
        elif шапка == КОЛОНКИ_ШАГОВ:
            метод.вид = "шаги"
            метод.строки = [Строка(проверить_имя(с[0], где), с[2], с[3], шаг=int(с[1]), при_сбое=с[4]) for с in таблица[1:]]
        elif шапка == КОЛОНКИ_ПРИМЕРОВ:
            метод.примеры = [Пример(с[0], с[1], с[2]) for с in таблица[1:]]
        else:
            raise ОшибкаСпецификации(f"{где}: таблица с колонками {шапка} здесь не ожидается")
    return метод


def прочитать_спецификации(папка: Path) -> dict[str, Объект]:
    объекты = {}
    for путь in sorted(папка.glob("*.md")):
        объект = разобрать_документ(путь)
        if объект.имя != путь.stem:
            raise ОшибкаСпецификации(f"{путь.name}: заголовок «{объект.имя}» не совпадает с именем файла")
        объекты[объект.имя] = объект
    определения: dict[str, str] = {}
    for объект in объекты.values():
        for имя in объект.перечисления:
            if имя in определения or имя in объекты:
                raise ОшибкаСпецификации(f"{объект.имя}: тип «{имя}» уже определён в {определения.get(имя, имя)}")
            определения[имя] = объект.имя
    for объект in объекты.values():
        if not объект.внешний:
            for метод in объект.методы.values():
                if метод.вид is None:
                    raise ОшибкаСпецификации(f"{объект.имя}: у метода {метод.имя} нет таблицы решений или шагов")
    return объекты
