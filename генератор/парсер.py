КОЛОНКИ_РЕШЕНИЙ = ["Правило", "Условие", "Действия", "Ответ"]
КОЛОНКИ_ШАГОВ = ["Правило", "Шаг", "Условие", "Действия", "Компенсация"]
КОЛОНКИ_ПРИМЕРОВ = ["Правило", "Реквизиты", "Параметры"]


def _шапка(таблица: list[list[str]]) -> list[str]:
    return [_без_ссылки(я) for я in таблица[0]]


ДАННЫЕ = "Реквизиты и инварианты"
ПОРЯДОК_РАЗДЕЛОВ = [ДАННЫЕ, "Методы", "Типы и перечисления", "Техническое соответствие"]
РАЗДЕЛЫ_С_ПОДРАЗДЕЛАМИ = [ДАННЫЕ, "Методы", "Типы и перечисления"]
ПУНКТ_РЕШЕНИЙ, ПУНКТ_ШАГОВ, ПУНКТ_ПРИМЕРОВ = "Решения", "Шаги", "Примеры"
РЕКВИЗИТЫ, ИНВАРИАНТЫ = "Реквизиты", "Инварианты"  # подразделы данных объекта и пункты вложенного типа


def _одна_таблица(элемент: Раздел, где: str) -> None:
    """В элементе документа — одна таблица или вложенные элементы."""
    if элемент.пункты and элемент.таблицы:
        raise ОшибкаСпецификации(f"{где}: в элементе документа одна таблица или вложенные элементы, а здесь и то и другое")
    if len(элемент.таблицы) > 1:
        raise ОшибкаСпецификации(f"{где}: в элементе документа одна таблица, а здесь {len(элемент.таблицы)}")


def разобрать_документ(путь: Path, файл: str | None = None) -> Объект:
    """файл — путь документа в сообщениях об ошибках, относительно папки спецификации."""
    файл = файл or путь.name
    имя, разделы = _разделы(путь.read_text(encoding="utf-8"), файл)
    объект = Объект(проверить_имя(имя, файл), путь)
    текущий = None
    встреченные: list[str] = []
    for раздел in разделы:
        где = f"{файл}: {раздел.заголовок}"
        if раздел.уровень == 4:
            continue  # пункты разбирает их подраздел
        if раздел.уровень == 2:
            текущий = раздел.заголовок
            if текущий == РЕКВИЗИТЫ:
                raise ОшибкаСпецификации(f"{где}: раздел «{РЕКВИЗИТЫ}» теперь «{ДАННЫЕ}» "
                                         f"с подразделами «{РЕКВИЗИТЫ}» и «{ИНВАРИАНТЫ}»")
            if текущий not in ПОРЯДОК_РАЗДЕЛОВ:
                raise ОшибкаСпецификации(f"{где}: неизвестный раздел")
            if встреченные and ПОРЯДОК_РАЗДЕЛОВ.index(текущий) <= ПОРЯДОК_РАЗДЕЛОВ.index(встреченные[-1]):
                raise ОшибкаСпецификации(f"{где}: разделы идут в порядке {', '.join(ПОРЯДОК_РАЗДЕЛОВ)}")
            встреченные.append(текущий)
            if текущий in РАЗДЕЛЫ_С_ПОДРАЗДЕЛАМИ and раздел.таблицы:
                raise ОшибкаСпецификации(f"{где}: до первого подраздела — только комментарий")
            _одна_таблица(раздел, где)
            if текущий == "Техническое соответствие":
                объект.свойства = _свойства(раздел.таблицы, где)
        elif текущий not in РАЗДЕЛЫ_С_ПОДРАЗДЕЛАМИ:
            if текущий is None:
                raise ОшибкаСпецификации(f"{где}: подраздел до первого раздела")
            raise ОшибкаСпецификации(f"{где}: у раздела «{текущий}» подразделов нет")
        elif текущий == ДАННЫЕ:
            _данные(объект, раздел, где)
        elif текущий == "Типы и перечисления":
            _одна_таблица(раздел, где)
            if раздел.пункты:
                _пункты_вложенного(раздел, где)
            else:
                объект.перечисления[раздел.заголовок] = _перечисление(раздел, где)
        elif текущий == "Методы":
            метод = _метод(раздел, где)
            объект.методы[метод.имя] = метод
    for обязательный in (ДАННЫЕ, "Техническое соответствие"):
        if обязательный not in встреченные:
            raise ОшибкаСпецификации(f"{файл}: нет раздела «{обязательный}»")
    if not any(р.уровень == 3 and р.заголовок == РЕКВИЗИТЫ for р in разделы):
        raise ОшибкаСпецификации(f"{файл}: {ДАННЫЕ}: нет подраздела «{РЕКВИЗИТЫ}»")
    return объект


КОЛОНКИ_СВОЙСТВ = ["Свойство", "Значение"]
СВОЙСТВА = ["Модуль", "Хранение", "Внешний"]


def _свойства(таблицы: list[list[list[str]]], где: str) -> dict[str, str]:
    """Таблица «Технического соответствия»: каждое свойство одной строкой, «Модуль» есть всегда."""
    if not таблицы:
        raise ОшибкаСпецификации(f"{где}: нет таблицы {' | '.join(КОЛОНКИ_СВОЙСТВ)}")
    шапка = _шапка(таблицы[0])
    if шапка != КОЛОНКИ_СВОЙСТВ:
        raise ОшибкаСпецификации(f"{где}: таблица с колонками {шапка} здесь не ожидается")
    свойства: dict[str, str] = {}
    for строка in таблицы[0][1:]:
        if len(строка) != len(КОЛОНКИ_СВОЙСТВ):
            raise ОшибкаСпецификации(f"{где}: строка «{строка[0]}»: колонок {len(строка)}, а в шапке {len(КОЛОНКИ_СВОЙСТВ)}")
        имя, значение = строка
        if имя not in СВОЙСТВА:
            raise ОшибкаСпецификации(f"{где}: свойство «{имя}» неизвестно: бывают {', '.join(СВОЙСТВА)}")
        if имя in свойства:
            raise ОшибкаСпецификации(f"{где}: свойство «{имя}» указано дважды")
        свойства[имя] = значение
    if "Модуль" not in свойства:
        raise ОшибкаСпецификации(f"{где}: нет свойства «Модуль»")
    if свойства.get("Внешний", "Да") != "Да":
        raise ОшибкаСпецификации(f"{где}: у свойства «Внешний» значение только «Да»")
    return свойства


def _данные(объект: Объект, раздел: Раздел, где: str) -> None:
    """Подразделы «Реквизиты» и «Инварианты» раздела «Реквизиты и инварианты»."""
    if раздел.пункты:
        raise ОшибкаСпецификации(f"{где}: у подраздела «{раздел.заголовок}» пунктов нет")
    if раздел.заголовок == РЕКВИЗИТЫ and any(_шапка(т) == КОЛОНКИ_ИНВАРИАНТОВ for т in раздел.таблицы):
        raise ОшибкаСпецификации(f"{где}: таблица инвариантов — в подразделе «{ИНВАРИАНТЫ}»")
    _одна_таблица(раздел, где)
    if раздел.заголовок == РЕКВИЗИТЫ and not объект.реквизиты:
        объект.реквизиты = _реквизиты(раздел.таблицы, где)
    elif раздел.заголовок == ИНВАРИАНТЫ and объект.реквизиты and not объект.инварианты:
        объект.инварианты = _инварианты(раздел.таблицы, где)
        if not объект.инварианты:
            raise ОшибкаСпецификации(f"{где}: нет таблицы {' | '.join(КОЛОНКИ_ИНВАРИАНТОВ)}")
    else:
        raise ОшибкаСпецификации(f"{где}: подразделы раздела «{ДАННЫЕ}» — «{РЕКВИЗИТЫ}», затем «{ИНВАРИАНТЫ}»")


КОЛОНКИ_РЕКВИЗИТОВ = ["Имя", "Описание", "Тип", "Ограничение"]
КОЛОНКИ_ИНВАРИАНТОВ = ["Правило", "Условие", "Ошибка"]


def _реквизиты(таблицы: list[list[list[str]]], где: str) -> list[Реквизит]:
    for таблица in таблицы:
        шапка = _шапка(таблица)
        if шапка == КОЛОНКИ_РЕКВИЗИТОВ:
            return [Реквизит(проверить_имя(с[0], где), с[1], разобрать_тип(с[2], f"{где}: {с[0]}"),
                             разобрать_ограничения(с[0], с[3], f"{где}: {с[0]}")) for с in таблица[1:]]
        if шапка == КОЛОНКИ_РЕКВИЗИТОВ[:3]:
            raise ОшибкаСпецификации(f"{где}: в таблице реквизитов четыре колонки: {' | '.join(КОЛОНКИ_РЕКВИЗИТОВ)}; "
                                     "«—» в «Ограничение», если ограничений нет")
    raise ОшибкаСпецификации(f"{где}: нет таблицы {' | '.join(КОЛОНКИ_РЕКВИЗИТОВ)}")


def _части(текст: str) -> list[str]:
    """Части ячейки через «;», точка с запятой внутри «текста» не делит."""
    части, текущая, в_строке = [], "", False
    for символ in текст:
        if символ == "«":
            в_строке = True
        elif символ == "»":
            в_строке = False
        if символ == ";" and not в_строке:
            части.append(текущая.strip())
            текущая = ""
        else:
            текущая += символ
    части.append(текущая.strip())
    return части


_СРАВНЕНИЯ = ("=", "≠", "<", ">", "≤", "≥", "∈", "∉")


def разобрать_ограничения(реквизит: str, ячейка: str, где: str) -> list[Ограничение]:
    """`≥ 18 «Только для взрослых»; ≤ 120` → ограничения; имя реквизита в условии опущено."""
    if ячейка.strip() in ("—", "-", ""):
        return []
    ограничения = []
    for часть in _части(ячейка):
        if not часть:
            raise ОшибкаСпецификации(f"{где}: пустое ограничение в «{ячейка}»")
        текст, ошибка = часть, None
        m = re.fullmatch(r"(.*?)\s*«([^«»]*)»", часть)
        if m and m.group(1).strip() not in _СРАВНЕНИЯ and not m.group(1).strip().endswith(_СРАВНЕНИЯ + ("[", ",")):
            текст, ошибка = m.group(1).strip(), m.group(2)
        if текст.startswith(_СРАВНЕНИЯ):
            выражение = f"{реквизит} {текст}"
        elif re.match(r"Длина\s*[=≠<>≤≥]", текст):
            выражение = f"Длина({реквизит}) {текст[len('Длина'):].strip()}"
        else:
            raise ОшибкаСпецификации(f"{где}: ограничение «{часть}» начинается со сравнения («≥ 0», «∈ [А, Б]») "
                                     "или с «Длина»; имя реквизита не пишется")
        ограничения.append(Ограничение(реквизит, текст, выражение, ошибка if ошибка is not None else f"{реквизит}: {текст}"))
    return ограничения


def _инварианты(таблицы: list[list[list[str]]], где: str) -> list[Инвариант]:
    for таблица in таблицы:
        шапка = _шапка(таблица)
        if шапка == КОЛОНКИ_ИНВАРИАНТОВ:
            инварианты = []
            for с in таблица[1:]:
                правило = проверить_имя(с[0], где)
                ошибка = с[2].strip()
                if ошибка in ("—", "-", ""):
                    ошибка = правило
                else:
                    m = re.fullmatch(r"«([^«»]*)»", ошибка)
                    if not m:
                        raise ОшибкаСпецификации(f"{где}: {правило}: в колонке Ошибка — текст в «» или «—»")
                    ошибка = m.group(1)
                инварианты.append(Инвариант(правило, с[1], ошибка))
            return инварианты
        if шапка == КОЛОНКИ_ИНВАРИАНТОВ[:2]:
            raise ОшибкаСпецификации(f"{где}: в таблице инвариантов три колонки: {' | '.join(КОЛОНКИ_ИНВАРИАНТОВ)}; "
                                     "«—» в «Ошибка» — текст по умолчанию, имя правила")
    return []


def _перечисление(раздел: Раздел, где: str) -> Перечисление:
    if any(_шапка(т) == КОЛОНКИ_РЕКВИЗИТОВ for т in раздел.таблицы):
        raise ОшибкаСпецификации(f"{где}: у вложенного типа реквизиты — в пункте «{РЕКВИЗИТЫ}»")
    for таблица in раздел.таблицы:
        if _шапка(таблица)[:2] == ["Имя", "Описание"]:
            return Перечисление(проверить_имя(раздел.заголовок, где), [(проверить_имя(с[0], где), с[1]) for с in таблица[1:]])
    raise ОшибкаСпецификации(f"{где}: нет таблицы перечисления")


def _пункты_вложенного(раздел: Раздел, где: str) -> None:
    """Вложенный тип: пункт «Реквизиты», за ним при необходимости «Инварианты»."""
    if [п.заголовок for п in раздел.пункты] not in ([РЕКВИЗИТЫ], [РЕКВИЗИТЫ, ИНВАРИАНТЫ]):
        raise ОшибкаСпецификации(f"{где}: пункты вложенного типа — «{РЕКВИЗИТЫ}», затем при необходимости «{ИНВАРИАНТЫ}»")
    for пункт in раздел.пункты:
        _одна_таблица(пункт, f"{где}: {пункт.заголовок}")


def _таблицы_метода(раздел: Раздел, где: str) -> list[list[list[str]]]:
    """Одна таблица — прямо в подразделе; две — каждая в свой пункт."""
    if len(раздел.таблицы) > 1:
        raise ОшибкаСпецификации(f"{где}: две таблицы — каждая в свой пункт: «#### {ПУНКТ_РЕШЕНИЙ}» или «#### {ПУНКТ_ШАГОВ}», "
                                 f"затем «#### {ПУНКТ_ПРИМЕРОВ}»")
    _одна_таблица(раздел, где)
    if not раздел.пункты:
        return раздел.таблицы
    имена = [п.заголовок for п in раздел.пункты]
    if len(имена) != 2 or имена[0] not in (ПУНКТ_РЕШЕНИЙ, ПУНКТ_ШАГОВ) or имена[1] != ПУНКТ_ПРИМЕРОВ:
        raise ОшибкаСпецификации(f"{где}: пункты метода — «{ПУНКТ_РЕШЕНИЙ}» или «{ПУНКТ_ШАГОВ}», затем «{ПУНКТ_ПРИМЕРОВ}»; "
                                 "одна таблица пишется прямо в подразделе")
    for пункт in раздел.пункты:
        if not пункт.таблицы:
            raise ОшибкаСпецификации(f"{где}: {пункт.заголовок}: в пункте нет таблицы")
        _одна_таблица(пункт, f"{где}: {пункт.заголовок}")
    поведение = _шапка(раздел.пункты[0].таблицы[0])
    ожидается = КОЛОНКИ_РЕШЕНИЙ if имена[0] == ПУНКТ_РЕШЕНИЙ else КОЛОНКИ_ШАГОВ
    if поведение != ожидается:
        raise ОшибкаСпецификации(f"{где}: {имена[0]}: шапка таблицы — {' | '.join(ожидается)}")
    return [п.таблицы[0] for п in раздел.пункты]


def _метод(раздел: Раздел, где: str) -> Метод:
    метод = разобрать_заголовок_метода(раздел.заголовок, где)
    for таблица in _таблицы_метода(раздел, где):
        шапка = _шапка(таблица)
        if шапка == КОЛОНКИ_РЕШЕНИЙ:
            метод.вид = "решения"
            метод.строки = [Строка(проверить_имя(с[0], где), с[1], с[2], ответ=с[3]) for с in таблица[1:]]
            if метод.строки and метод.строки[-1].условие != "—":
                raise ОшибкаСпецификации(f"{где}: последняя строка таблицы решений должна быть без условия")
        elif шапка == КОЛОНКИ_ШАГОВ:
            метод.вид = "шаги"
            метод.строки = [Строка(проверить_имя(с[0], где), с[2], с[3], шаг=int(с[1]), компенсация=с[4]) for с in таблица[1:]]
            if метод.строки and метод.строки[-1].компенсация.strip() not in ("—", "-", ""):
                raise ОшибкаСпецификации(f"{где}: строка «{метод.строки[-1].правило}»: у последнего шага компенсации нет — после него падать нечему")
        elif "Эффект" in шапка or "Итог" in шапка:
            raise ОшибкаСпецификации(f"{где}: колонки «Эффект» и «Итог» переименованы в «Действия» и «Ответ»")
        elif шапка == КОЛОНКИ_ШАГОВ[:4] + ["При сбое"]:
            raise ОшибкаСпецификации(f"{где}: колонка «При сбое» теперь «Компенсация» — как отменить этот шаг, если упадёт один из следующих")
        elif шапка == КОЛОНКИ_ПРИМЕРОВ:
            метод.примеры = [Пример(с[0], с[1], с[2]) for с in таблица[1:]]
        else:
            raise ОшибкаСпецификации(f"{где}: таблица с колонками {шапка} здесь не ожидается")
    for строка in метод.строки:
        if any(re.search(r"\bПрежнее\s*\(", re.sub(r"«[^»]*»", "", я)) for я in (строка.условие, строка.действия, строка.ответ)):
            raise ОшибкаСпецификации(f"{где}: строка «{строка.правило}»: «Прежнее(…)» бывает только в колонке Компенсация")
    return метод


ПРЕДЛАГАЕМЫЕ_ИЗМЕНЕНИЯ = "предлагаемые-изменения"


def прочитать_спецификации(папка: Path) -> dict[str, Объект]:
    объекты = {}
    файлы: dict[str, str] = {}
    for путь in sorted(папка.rglob("*.md")):
        файл = путь.relative_to(папка).as_posix()
        if ПРЕДЛАГАЕМЫЕ_ИЗМЕНЕНИЯ in путь.relative_to(папка).parts[:-1]:
            continue  # ФайлыСпецификации: тесты только по действующим документам
        объект = разобрать_документ(путь, файл)
        if объект.имя != путь.stem:
            raise ОшибкаСпецификации(f"{файл}: заголовок «{объект.имя}» не совпадает с именем файла")
        if объект.имя in объекты:
            raise ОшибкаСпецификации(f"объект «{объект.имя}» описан дважды: {файлы[объект.имя]} и {файл}")
        объекты[объект.имя] = объект
        файлы[объект.имя] = файл
    определения: dict[str, str] = {}
    for объект in объекты.values():
        for имя in объект.перечисления:
            if имя in определения or имя in объекты:
                raise ОшибкаСпецификации(f"{объект.имя}: тип «{имя}» уже определён в {определения.get(имя, имя)}")
            определения[имя] = объект.имя
    for объект in объекты.values():
        if not объект.внешний:
            for метод in объект.методы.values():
                if метод.вид is None:
                    raise ОшибкаСпецификации(f"{объект.имя}: у метода {метод.имя} нет таблицы решений или шагов")
    return объекты
