"""Чтение документов спецификации в модель: объекты, реквизиты, перечисления, методы."""
from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path


class ОшибкаСпецификации(Exception):
    """Документ не соответствует стандарту; текст говорит, где и что."""


@dataclass
class Тип:
    вид: str                      # Строка, Число, Булево, Дата, Ссылка, Список
    цель: str | None = None       # имя объекта или перечисления для Ссылка
    элемент: Тип | None = None    # тип элемента для Список
    длина: int | None = None
    точность: int = 0
    необязательный: bool = False
    по_умолчанию: str | None = None   # исходный текст выражения после "="

    def __str__(self) -> str:
        if self.вид == "Ссылка":
            основа = f'Ссылка."{self.цель}"'
        elif self.вид == "Список":
            основа = f"Список.{self.элемент}"
        elif self.вид == "Число":
            основа = f"Число({self.длина},{self.точность})"
        elif self.вид == "Строка" and self.длина:
            основа = f"Строка({self.длина})"
        else:
            основа = self.вид
        return основа + ("?" if self.необязательный else "")


@dataclass
class Ограничение:
    """Условие на один реквизит из колонки «Ограничение»."""
    реквизит: str
    текст: str        # как записано, без текста ошибки: «≥ 18»
    выражение: str    # с именем реквизита: «Возраст ≥ 18»
    ошибка: str       # текст ошибки: свой или «Возраст: ≥ 18»


@dataclass
class Инвариант:
    """Строка таблицы «Правило | Условие | Ошибка» под реквизитами."""
    правило: str
    условие: str
    ошибка: str


@dataclass
class Реквизит:
    имя: str
    описание: str
    тип: Тип
    ограничения: list[Ограничение] = field(default_factory=list)


@dataclass
class Перечисление:
    имя: str
    значения: list[tuple[str, str]]   # (имя, описание)


@dataclass
class Параметр:
    имя: str
    тип: Тип


@dataclass
class Строка:
    """Строка таблицы решений или шагов; ячейки — исходный текст."""
    правило: str
    условие: str
    действия: str
    ответ: str = "—"        # у таблицы решений
    шаг: int | None = None  # у таблицы шагов
    компенсация: str = "—"  # у таблицы шагов


@dataclass
class Пример:
    правило: str
    реквизиты: str
    параметры: str


@dataclass
class Метод:
    имя: str
    параметры: list[Параметр]
    тип_ответа: Тип | None
    вид: str | None = None          # "решения", "шаги" или None у внешнего объекта
    строки: list[Строка] = field(default_factory=list)
    примеры: list[Пример] = field(default_factory=list)


@dataclass
class Объект:
    имя: str
    путь: Path
    реквизиты: list[Реквизит] = field(default_factory=list)
    инварианты: list[Инвариант] = field(default_factory=list)
    перечисления: dict[str, Перечисление] = field(default_factory=dict)
    методы: dict[str, Метод] = field(default_factory=dict)
    свойства: dict[str, str] = field(default_factory=dict)

    @property
    def внешний(self) -> bool:
        return self.свойства.get("Внешний") == "Да"

    def реквизит(self, имя: str) -> Реквизит | None:
        return next((р for р in self.реквизиты if р.имя == имя), None)


# ---------------------------------------------------------------- markdown

@dataclass
class Раздел:
    уровень: int
    заголовок: str
    таблицы: list[list[list[str]]] = field(default_factory=list)  # таблица = строки = ячейки
    пункты: list["Раздел"] = field(default_factory=list)  # у подраздела: пункты «####»


_ССЫЛКА = re.compile(r"\[([^\]]*)\]\([^)]*\)")


def _ячейки(строка: str) -> list[str]:
    тело = строка.strip()
    if тело.startswith("|"):
        тело = тело[1:]
    if тело.endswith("|"):
        тело = тело[:-1]
    return [я.strip().replace("\\|", "|") for я in re.split(r"(?<!\\)\|", тело)]


_ИМЯ = re.compile(r"[A-ZА-ЯЁ][A-Za-zА-Яа-яЁё0-9]*")


def проверить_имя(имя: str, где: str) -> str:
    if not _ИМЯ.fullmatch(имя):
        raise ОшибкаСпецификации(f"{где}: имя «{имя}» — с заглавной буквы, только буквы и цифры")
    return имя


def _разделы(текст: str, файл: str) -> tuple[str, list[Раздел]]:
    заголовок_документа = None
    назначение_есть = False
    разделы: list[Раздел] = []
    текущая_таблица: list[list[str]] | None = None
    for номер, строка in enumerate(текст.splitlines(), 1):
        if заголовок_документа is not None and not разделы and строка.strip() and not назначение_есть:
            if not строка.startswith("\\#"):
                raise ОшибкаСпецификации(f"{файл}: после заголовка ожидается комментарий о назначении (строка «\\# …»)")
            назначение_есть = True
            continue
        if строка.startswith("|"):
            ячейки = _ячейки(строка)
            if all(re.fullmatch(r":?-+:?", я) for я in ячейки if я):
                continue  # разделитель шапки
            if текущая_таблица is None:
                текущая_таблица = []
                if not разделы:
                    raise ОшибкаСпецификации(f"{файл}: таблица до первого раздела")
                разделы[-1].таблицы.append(текущая_таблица)
            текущая_таблица.append(ячейки)
            continue
        текущая_таблица = None
        m = re.match(r"^(#{1,4})\s+(.*)$", строка)
        if m:
            уровень = len(m.group(1))
            if уровень == 1:
                заголовок_документа = m.group(2).strip()
            elif уровень == 4:
                подраздел = next((р for р in reversed(разделы) if р.уровень < 4), None)
                if подраздел is None or подраздел.уровень == 2:
                    raise ОшибкаСпецификации(f"{файл}, строка {номер}: пункт «{m.group(2).strip()}» бывает только в подразделе")
                пункт = Раздел(4, m.group(2).strip())
                подраздел.пункты.append(пункт)
                разделы.append(пункт)
            else:
                разделы.append(Раздел(уровень, m.group(2).strip()))
        elif строка.startswith("#####"):
            raise ОшибкаСпецификации(
                f"{файл}, строка {номер}: заголовок «{строка.strip()}» — заголовки бывают только «#», «##», «###» и «####»")
        elif строка.strip() and not строка.startswith("\\#"):
            raise ОшибкаСпецификации(
                f"{файл}, строка {номер}: текст вне таблицы «{строка.strip()}» — "
                "правило пишется строкой таблицы, пояснение — комментарием «\\# …»")
    if заголовок_документа is None:
        raise ОшибкаСпецификации(f"{файл}: нет заголовка документа")
    if not назначение_есть:
        raise ОшибкаСпецификации(f"{файл}: нет комментария о назначении после заголовка")
    return заголовок_документа, разделы


# ---------------------------------------------------------------- типы

def _без_ссылки(текст: str) -> str:
    return _ССЫЛКА.sub(r"\1", текст).strip()


def разобрать_тип(текст: str, где: str) -> Тип:
    текст = _без_ссылки(текст)
    по_умолчанию = None
    m = re.match(r"^(.*?)\s*=\s*(.+)$", текст)
    if m:
        текст, по_умолчанию = m.group(1).strip(), m.group(2).strip()
    необязательный = текст.endswith("?")
    if необязательный:
        текст = текст[:-1].strip()
    тип = _разобрать_основу(текст, где)
    тип.необязательный = необязательный
    тип.по_умолчанию = по_умолчанию
    return тип


def _разобрать_основу(текст: str, где: str) -> Тип:
    if текст == "Булево" or текст == "Дата":
        return Тип(текст)
    m = re.fullmatch(r"Строка(?:\((\d+)\))?", текст)
    if m:
        return Тип("Строка", длина=int(m.group(1)) if m.group(1) else None)
    if re.fullmatch(r"Число\(.*,\s*Неотрицательное\)", текст):
        raise ОшибкаСпецификации(f"{где}: «Неотрицательное» убрано из типа — у реквизита ограничение «≥ 0» в колонке Ограничение, "
                                 "у параметра — строка метода с ошибкой")
    m = re.fullmatch(r"Число\((\d+)(?:,\s*(\d+))?\)", текст)
    if m:
        return Тип("Число", длина=int(m.group(1)), точность=int(m.group(2) or 0))
    m = re.fullmatch(r'Ссылка\."([^"]+)"', текст)
    if m:
        return Тип("Ссылка", цель=m.group(1))
    m = re.fullmatch(r"Список\.(.+)", текст)
    if m:
        return Тип("Список", элемент=_разобрать_основу(m.group(1), где))
    raise ОшибкаСпецификации(f"{где}: неизвестный тип «{текст}»")


def _разбить_параметры(текст: str) -> list[str]:
    части, глубина, текущая = [], 0, ""
    for символ in текст:
        if символ == "(":
            глубина += 1
        elif символ == ")":
            глубина -= 1
        if символ == "," and глубина == 0:
            части.append(текущая)
            текущая = ""
        else:
            текущая += символ
    if текущая.strip():
        части.append(текущая)
    return [ч.strip() for ч in части]


def разобрать_заголовок_метода(заголовок: str, где: str) -> Метод:
    текст = заголовок.strip()
    m = re.match(r"([^\s(]+)\(", текст)
    глубина, конец = 0, None
    for i, символ in enumerate(текст):
        if символ == "(":
            глубина += 1
        elif символ == ")":
            глубина -= 1
            if глубина == 0:
                конец = i
                break
    if not m or конец is None:
        raise ОшибкаСпецификации(f"{где}: заголовок метода «{заголовок}» не вида Имя(Параметр: Тип): Тип")
    имя_метода = m.group(1)
    внутри = текст[m.end():конец]
    хвост = текст[конец + 1:].strip()
    параметры = []
    for часть in _разбить_параметры(внутри):
        if ":" not in часть:
            raise ОшибкаСпецификации(f"{где}: у параметра «{часть}» метода {имя_метода} нет типа")
        имя, тип = часть.split(":", 1)
        параметры.append(Параметр(имя.strip(), разобрать_тип(тип.strip(), где)))
    тип_ответа = None
    if хвост:
        if not хвост.startswith(":"):
            raise ОшибкаСпецификации(f"{где}: после скобок метода {имя_метода} ожидается «: Тип»")
        тип_ответа = разобрать_тип(хвост[1:].strip(), где)
    for параметр in параметры:
        проверить_имя(параметр.имя, где)
    return Метод(проверить_имя(имя_метода, где), параметры, тип_ответа)


