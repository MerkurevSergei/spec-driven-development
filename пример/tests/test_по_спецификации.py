import unittest
from datetime import datetime

from tests import привязка


class ТестыПоСпецификации(unittest.TestCase):

    def test_Задача_Реквизиты(self):
        внешний_почта = привязка.внешний('Почта')
        объект = привязка.создать('Задача', {'Название': 'Название', 'Статус': 'Открыта', 'ДатаЗакрытия': None, 'Срочная': False, 'Адрес': 'Адрес', 'Почта': внешний_почта})
        self.assertEqual(привязка.прочитать(объект), {'Название': 'Название', 'Статус': 'Открыта', 'ДатаЗакрытия': None, 'Срочная': False, 'Адрес': 'Адрес'})

